"""Safely publish and temporarily hide slimtest-generated YAML artifacts."""

from __future__ import annotations

import json
import os
import shutil
import tempfile
import threading
from collections.abc import Iterator, Mapping
from contextlib import contextmanager
from dataclasses import dataclass
from pathlib import Path
from typing import Any, TextIO

from .config import load_config
from .factory import SlimTestError

GENERATED_FILE_SUFFIX = ".generated.yml"
SOURCE_MAP_FILENAME = "source_map.json"
GENERATED_HEADER = "# Generated by slimtest. DO NOT EDIT.\n"
INVENTORY_FILENAME = ".slimtest-artifacts.json"

_INVENTORY_VERSION = 1
_PROCESS_LOCKS: dict[Path, threading.RLock] = {}
_PROCESS_LOCKS_GUARD = threading.Lock()
_LOCK_STATE = threading.local()


class ArtifactOwnershipError(SlimTestError):
    """A generated filename is occupied by a file slimtest does not own."""


class ArtifactPublishError(SlimTestError):
    """Publishing failed; restoration status is included in the message."""

    def __init__(self, message: str, *, recovery_dir: Path | None = None) -> None:
        super().__init__(message)
        self.recovery_dir = recovery_dir


@dataclass
class HiddenGeneratedYml:
    """Handle for a temporarily hidden set of generated YAML files.

    The context restores the old files unless ``commit`` is called. A runner
    calls ``commit`` only after compilation has successfully published the
    replacement set.
    """

    _committed: bool = False

    def commit(self) -> None:
        """Keep replacement artifacts and discard the hidden old YAML files."""
        self._committed = True


def publish_artifacts(output_dir: Path, rendered: Mapping[str, str]) -> None:
    """Publish a rendered artifact set into ``output_dir`` with rollback.

    Rendering happens before this function is called. Files are first written
    to a sibling staging directory. Existing artifacts are moved to a backup
    before staged files are installed. Cooperating publishers are serialized,
    and a failed install restores the complete prior set. Files outside
    slimtest's inventory are left alone.
    """
    output_dir = output_dir.resolve()
    _validate_names(rendered)

    generated_names = sorted(
        name for name in rendered if name.endswith(GENERATED_FILE_SUFFIX)
    )
    complete_rendered = dict(rendered)
    complete_rendered[INVENTORY_FILENAME] = _render_inventory(generated_names)

    stage_dir: Path | None = None
    backup_dir: Path | None = None
    try:
        output_dir.parent.mkdir(parents=True, exist_ok=True)
        stage_dir = Path(
            tempfile.mkdtemp(
                prefix=f".{output_dir.name}.slimtest-stage-", dir=output_dir.parent
            )
        )
        for name, content in complete_rendered.items():
            (stage_dir / name).write_text(content, encoding="utf-8")

        with _artifact_lock(output_dir):
            output_dir.mkdir(parents=True, exist_ok=True)
            owned = {path.name for path in owned_generated_yml(output_dir)}
            desired_generated = set(generated_names)
            for name in desired_generated:
                target = output_dir / name
                if target.exists() and name not in owned:
                    raise ArtifactOwnershipError(
                        f"refusing to overwrite {target}: it is not marked as "
                        "generated by slimtest"
                    )

            stale = owned - desired_generated
            backup_dir = Path(
                tempfile.mkdtemp(
                    prefix=f".{output_dir.name}.slimtest-backup-",
                    dir=output_dir.parent,
                )
            )
            _install_staged(output_dir, stage_dir, backup_dir, complete_rendered, stale)
    except ArtifactPublishError as exc:
        if exc.recovery_dir == backup_dir:
            backup_dir = None
        raise
    except OSError as exc:
        raise ArtifactPublishError(
            f"failed to stage or publish slimtest artifacts: {exc}"
        ) from exc
    finally:
        if stage_dir is not None:
            shutil.rmtree(stage_dir, ignore_errors=True)
        if backup_dir is not None:
            shutil.rmtree(backup_dir, ignore_errors=True)


def owned_generated_yml(output_dir: Path) -> list[Path]:
    """Return existing YAML files that are verifiably owned by slimtest."""
    if not output_dir.is_dir():
        return []

    candidates = set(_inventory_names(output_dir))
    candidates.update(
        path.name for path in output_dir.glob(f"*{GENERATED_FILE_SUFFIX}")
    )
    owned: list[Path] = []
    for name in sorted(candidates):
        if not _is_safe_generated_name(name):
            continue
        path = output_dir / name
        if path.is_file() and not path.is_symlink() and _has_generated_header(path):
            owned.append(path)
    return owned


@contextmanager
def temporarily_hide_generated_yml(
    project_root: Path,
) -> Iterator[HiddenGeneratedYml]:
    """Hide owned generated YAML while dbt refreshes its manifest.

    The old files are restored on exceptions and on ordinary exit unless the
    caller calls ``commit`` after a successful compile. This prevents stale
    YAML for a deleted model from breaking the initial ``dbt parse`` while
    retaining the last good output if compilation fails.
    """
    project_root = project_root.resolve()
    config = load_config(project_root)
    output_dir = (project_root / config.generated_yml_path).resolve()
    handle = HiddenGeneratedYml()

    try:
        output_dir.parent.mkdir(parents=True, exist_ok=True)
        hidden_dir = Path(
            tempfile.mkdtemp(
                prefix=f".{output_dir.name}.slimtest-hidden-", dir=output_dir.parent
            )
        )
    except OSError as exc:
        raise ArtifactPublishError(
            f"failed to prepare generated YAML for dbt parse: {exc}"
        ) from exc

    hidden: list[str] = []
    cleanup_hidden = True
    try:
        with _artifact_lock(output_dir):
            try:
                for path in owned_generated_yml(output_dir):
                    _replace_path(path, hidden_dir / path.name)
                    hidden.append(path.name)
            except Exception as exc:
                rollback_errors = _restore_hidden(
                    output_dir, hidden_dir, reversed(hidden)
                )
                if rollback_errors:
                    cleanup_hidden = False
                    raise ArtifactPublishError(
                        "failed to hide generated YAML and restoration is incomplete; "
                        f"recovery files retained at {hidden_dir}",
                        recovery_dir=hidden_dir,
                    ) from exc
                raise ArtifactPublishError(
                    f"failed to hide generated YAML for dbt parse: {exc}"
                ) from exc

            try:
                yield handle
            finally:
                if not handle._committed:
                    rollback_errors: list[Exception] = []
                    for current in owned_generated_yml(output_dir):
                        try:
                            current.unlink()
                        except OSError as exc:
                            rollback_errors.append(exc)
                    rollback_errors.extend(
                        _restore_hidden(output_dir, hidden_dir, iter(hidden))
                    )
                    if rollback_errors:
                        cleanup_hidden = False
                        raise ArtifactPublishError(
                            "failed to restore generated YAML; restoration is "
                            "incomplete and recovery files are retained at "
                            f"{hidden_dir}",
                            recovery_dir=hidden_dir,
                        ) from rollback_errors[0]
    finally:
        if cleanup_hidden:
            shutil.rmtree(hidden_dir, ignore_errors=True)


def _install_staged(
    output_dir: Path,
    stage_dir: Path,
    backup_dir: Path,
    rendered: Mapping[str, str],
    stale: set[str],
) -> None:
    backup_names: list[str] = []
    installed_names: list[str] = []
    replace_names = set(rendered) | stale
    try:
        for name in sorted(replace_names):
            target = output_dir / name
            if target.exists():
                if not target.is_file():
                    raise ArtifactPublishError(
                        f"cannot publish slimtest artifact over non-file {target}"
                    )
                _replace_path(target, backup_dir / name)
                backup_names.append(name)

        for name in sorted(rendered):
            _replace_path(stage_dir / name, output_dir / name)
            installed_names.append(name)
    except Exception as exc:
        rollback_errors: list[Exception] = []
        for name in reversed(installed_names):
            try:
                (output_dir / name).unlink(missing_ok=True)
            except Exception as rollback_exc:  # noqa: BLE001
                rollback_errors.append(rollback_exc)
        for name in reversed(backup_names):
            try:
                _replace_path(backup_dir / name, output_dir / name)
            except Exception as rollback_exc:  # noqa: BLE001
                rollback_errors.append(rollback_exc)
        if rollback_errors:
            raise ArtifactPublishError(
                "failed to publish slimtest artifacts; restoration is incomplete and "
                f"recovery files are retained at {backup_dir}",
                recovery_dir=backup_dir,
            ) from exc
        raise ArtifactPublishError(
            "failed to publish slimtest artifacts; restored previous output"
        ) from exc


def _validate_names(rendered: Mapping[str, str]) -> None:
    reserved = {INVENTORY_FILENAME}
    for name in rendered:
        if (
            Path(name).name != name
            or "/" in name
            or "\\" in name
            or not name
            or name in reserved
        ):
            raise ArtifactPublishError(f"invalid generated artifact name: {name!r}")


def _restore_hidden(
    output_dir: Path, hidden_dir: Path, names: Iterator[str]
) -> list[Exception]:
    errors: list[Exception] = []
    try:
        output_dir.mkdir(parents=True, exist_ok=True)
    except OSError as exc:
        return [exc]
    for name in names:
        source = hidden_dir / name
        if not source.exists():
            continue
        try:
            _replace_path(source, output_dir / name)
        except OSError as exc:
            errors.append(exc)
    return errors


def _render_inventory(generated_names: list[str]) -> str:
    return (
        json.dumps(
            {"version": _INVENTORY_VERSION, "generated_yml": generated_names},
            indent=2,
            sort_keys=True,
        )
        + "\n"
    )


def _inventory_names(output_dir: Path) -> list[str]:
    path = output_dir / INVENTORY_FILENAME
    try:
        data: Any = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, UnicodeError, json.JSONDecodeError):
        return []
    if not isinstance(data, dict) or data.get("version") != _INVENTORY_VERSION:
        return []
    names = data.get("generated_yml")
    if not isinstance(names, list):
        return []
    return [name for name in names if isinstance(name, str)]


def _is_safe_generated_name(name: str) -> bool:
    return Path(name).name == name and name.endswith(GENERATED_FILE_SUFFIX)


def _has_generated_header(path: Path) -> bool:
    try:
        with path.open("r", encoding="utf-8") as stream:
            return stream.read(len(GENERATED_HEADER)) == GENERATED_HEADER
    except (OSError, UnicodeError):
        return False


@contextmanager
def _artifact_lock(output_dir: Path) -> Iterator[None]:
    """Serialize a generated-output transaction across threads and processes."""
    key = output_dir.resolve()
    with _PROCESS_LOCKS_GUARD:
        process_lock = _PROCESS_LOCKS.setdefault(key, threading.RLock())

    with process_lock:
        depths: dict[Path, tuple[int, TextIO]] = getattr(_LOCK_STATE, "depths", {})
        _LOCK_STATE.depths = depths
        existing = depths.get(key)
        if existing is not None:
            depths[key] = (existing[0] + 1, existing[1])
            try:
                yield
            finally:
                depth, stream = depths[key]
                depths[key] = (depth - 1, stream)
            return

        lock_path = output_dir.parent / f".{output_dir.name}.slimtest.lock"
        stream = lock_path.open("a+", encoding="utf-8")
        _lock_file(stream)
        depths[key] = (1, stream)
        try:
            yield
        finally:
            depths.pop(key, None)
            _unlock_file(stream)
            stream.close()


def _lock_file(stream: TextIO) -> None:
    if os.name == "nt":  # pragma: no cover - exercised on Windows CI
        import msvcrt

        stream.seek(0)
        stream.write("0")
        stream.flush()
        msvcrt.locking(  # type: ignore[attr-defined]
            stream.fileno(),
            msvcrt.LK_LOCK,
            1,  # type: ignore[attr-defined]
        )
    else:
        import fcntl

        fcntl.flock(stream.fileno(), fcntl.LOCK_EX)


def _unlock_file(stream: TextIO) -> None:
    if os.name == "nt":  # pragma: no cover - exercised on Windows CI
        import msvcrt

        stream.seek(0)
        msvcrt.locking(  # type: ignore[attr-defined]
            stream.fileno(),
            msvcrt.LK_UNLCK,
            1,  # type: ignore[attr-defined]
        )
    else:
        import fcntl

        fcntl.flock(stream.fileno(), fcntl.LOCK_UN)


def _replace_path(source: Path, destination: Path) -> None:
    os.replace(source, destination)


